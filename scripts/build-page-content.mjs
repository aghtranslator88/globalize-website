#!/usr/bin/env node
// Builds src/content/pageContent.ts from the editorial Markdown files in
// content/pages/{ar,en}/*.md and content/guides/{ar,en}/*.md.
//
// Each Markdown file has YAML-ish frontmatter (seo_title, meta_description, ...),
// one "# " H1, an optional short answer (a "> " blockquote or a paragraph that
// starts with "**Short answer:**" / "**الإجابة المختصرة:**"), body sections, and
// a final "## " FAQ section whose "### " headings are the questions.
//
// Run after editing any of those files:  node scripts/build-page-content.mjs

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const LOCALES = ["ar", "en"];

function parseFrontmatter(raw) {
  const match = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) return { meta: {}, body: raw };
  const meta = {};
  for (const line of match[1].split("\n")) {
    const m = line.match(/^([a-z_]+):\s*(.*)$/i);
    if (!m) continue;
    meta[m[1]] = m[2].trim().replace(/^"(.*)"$/, "$1");
  }
  return { meta, body: raw.slice(match[0].length) };
}

// Lines that only make sense in the editorial package, not on the rendered page.
function stripPackageOnlyLines(markdown) {
  return markdown
    .split("\n")
    .filter((line) => !/^\s*-\s*\*\*CTA:\*\*/.test(line))
    .join("\n");
}

function parseUnit(raw) {
  const { meta, body } = parseFrontmatter(raw);
  const lines = stripPackageOnlyLines(body).split("\n");

  const h1Index = lines.findIndex((l) => /^#\s+/.test(l));
  if (h1Index === -1) throw new Error("missing H1");
  const h1 = lines[h1Index].replace(/^#\s+/, "").trim();
  let rest = lines.slice(h1Index + 1);

  // Short answer: first non-empty block after the H1.
  let shortAnswer = "";
  const firstIdx = rest.findIndex((l) => l.trim() !== "");
  if (firstIdx !== -1) {
    const first = rest[firstIdx].trim();
    const isShortAnswer =
      first.startsWith(">") || /^\*\*(Short answer|الإجابة المختصرة)/i.test(first);
    if (isShortAnswer) {
      let end = firstIdx;
      const block = [];
      while (end < rest.length && rest[end].trim() !== "") {
        block.push(rest[end].trim().replace(/^>\s?/, ""));
        end++;
      }
      shortAnswer = block
        .join(" ")
        .replace(/^\*\*(Short answer|الإجابة المختصرة):?\*\*:?\s*/i, "")
        .trim();
      rest = rest.slice(end);
    }
  }

  // FAQ: the last "## " section, when its "### " headings are questions.
  const h2Indexes = rest.map((l, i) => (/^##\s+/.test(l) ? i : -1)).filter((i) => i !== -1);
  let faqs = [];
  let faqHeading = "";
  if (h2Indexes.length) {
    const lastH2 = h2Indexes[h2Indexes.length - 1];
    const section = rest.slice(lastH2 + 1);
    const items = [];
    let current = null;
    for (const line of section) {
      const q = line.match(/^###\s+(.+)$/);
      if (q) {
        if (current) items.push(current);
        current = { question: q[1].trim(), answer: [] };
      } else if (current) {
        current.answer.push(line);
      }
    }
    if (current) items.push(current);
    const looksLikeFaq = items.length >= 2 && items.every((it) => /[?؟]\s*$/.test(it.question));
    if (looksLikeFaq) {
      faqHeading = rest[lastH2].replace(/^##\s+/, "").trim();
      faqs = items.map((it) => ({
        question: it.question,
        answer: it.answer.join("\n").trim(),
      }));
      rest = rest.slice(0, lastH2);
    }
  }

  return {
    seoTitle: meta.seo_title || h1,
    metaDescription: meta.meta_description || "",
    h1,
    shortAnswer,
    body: rest.join("\n").trim(),
    faqHeading,
    faqs,
  };
}

function loadDir(dir) {
  const out = {};
  for (const locale of LOCALES) {
    const full = path.join(ROOT, dir, locale);
    for (const file of fs.readdirSync(full).filter((f) => f.endsWith(".md")).sort()) {
      const key = file.replace(/\.md$/, "");
      try {
        out[key] ??= {};
        out[key][locale] = parseUnit(fs.readFileSync(path.join(full, file), "utf8"));
      } catch (err) {
        throw new Error(`${dir}/${locale}/${file}: ${err.message}`);
      }
    }
  }
  return out;
}

const pages = loadDir("content/pages");
const guides = loadDir("content/guides");

for (const [group, data] of Object.entries({ pages, guides })) {
  for (const [key, byLocale] of Object.entries(data)) {
    for (const locale of LOCALES) {
      const unit = byLocale[locale];
      if (!unit) throw new Error(`${group}/${key}: missing ${locale}`);
      if (unit.faqs.length !== 4) console.warn(`warn: ${group}/${key}/${locale} has ${unit.faqs.length} FAQs`);
      if (!unit.shortAnswer) console.warn(`note: ${group}/${key}/${locale} has no short answer block`);
    }
  }
}

const header = `// AUTO-GENERATED by scripts/build-page-content.mjs — do not edit by hand.
// Source: content/pages/**/*.md and content/guides/**/*.md

export interface PageContentFaq {
  question: string;
  answer: string;
}

export interface PageContentUnit {
  seoTitle: string;
  metaDescription: string;
  h1: string;
  shortAnswer: string;
  body: string;
  faqHeading: string;
  faqs: PageContentFaq[];
}

export type LocalizedUnit = Record<"ar" | "en", PageContentUnit>;
`;

const file =
  header +
  `\nexport const PAGE_CONTENT = ${JSON.stringify(pages, null, 2)} satisfies Record<string, LocalizedUnit>;\n` +
  `\nexport const GUIDE_CONTENT = ${JSON.stringify(guides, null, 2)} satisfies Record<string, LocalizedUnit>;\n` +
  `\nexport type PageContentKey = keyof typeof PAGE_CONTENT;\nexport type GuideContentKey = keyof typeof GUIDE_CONTENT;\n`;

fs.writeFileSync(path.join(ROOT, "src/content/pageContent.ts"), file);
console.log(`wrote ${Object.keys(pages).length} pages and ${Object.keys(guides).length} guides`);
